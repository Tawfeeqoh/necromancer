import shutil
import subprocess
from pathlib import Path
from typing import Optional, Tuple
from backend.app.config import UPLOADS_DIR, WORKSPACES_DIR


class WorkspaceManager:
    @staticmethod
    def get_upload_extracted_dir(upload_id: str) -> Path:
        return UPLOADS_DIR / upload_id / "extracted"

    @staticmethod
    def get_project_workspace_dir(project_id: str) -> Path:
        return WORKSPACES_DIR / project_id

    @classmethod
    def setup_project_workspace(cls, project_id: str, upload_id: str) -> Path:
        source_dir = cls.get_upload_extracted_dir(upload_id)
        if not source_dir.exists():
            raise FileNotFoundError(f"Source directory for upload {upload_id} not found.")

        workspace_dir = cls.get_project_workspace_dir(project_id)
        if workspace_dir.exists():
            shutil.rmtree(workspace_dir, ignore_errors=True)

        entries = list(source_dir.iterdir())
        actual_source = source_dir
        if len(entries) == 1 and entries[0].is_dir():
            actual_source = entries[0]

        shutil.copytree(actual_source, workspace_dir)

        # Normalize line endings in extracted files to LF and ensure a trailing
        # newline so that unified diffs generated by difflib are always valid
        # for `git apply` (no "corrupt patch" or "no newline at end" errors).
        for p in workspace_dir.rglob("*"):
            if p.is_file() and p.suffix.lower() in {".php", ".sql", ".json", ".md", ".txt", ".js", ".css", ".html"}:
                try:
                    text = p.read_text(encoding="utf-8", errors="ignore")
                    text = text.replace("\r\n", "\n")
                    if text and not text.endswith("\n"):
                        text += "\n"
                    p.write_text(text, encoding="utf-8", newline="\n")
                except Exception:
                    pass

        subprocess.run(["git", "init", "-b", "main"], cwd=workspace_dir, check=True, capture_output=True)
        subprocess.run(["git", "config", "core.autocrlf", "false"], cwd=workspace_dir, check=True, capture_output=True)
        subprocess.run(["git", "config", "user.name", "Necromancer Agent"], cwd=workspace_dir, check=True, capture_output=True)
        subprocess.run(["git", "config", "user.email", "agent@necromancer.local"], cwd=workspace_dir, check=True, capture_output=True)
        subprocess.run(["git", "add", "."], cwd=workspace_dir, check=True, capture_output=True)
        subprocess.run(["git", "commit", "-m", "Baseline: unrevived legacy state"], cwd=workspace_dir, check=True, capture_output=True)

        return workspace_dir

    @classmethod
    def get_head_commit(cls, project_id: str) -> str:
        workspace_dir = cls.get_project_workspace_dir(project_id)
        res = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=workspace_dir,
            capture_output=True,
            text=True,
            check=True,
        )
        return res.stdout.strip()

    @classmethod
    def validate_patch_in_workspace(cls, project_id: str, patch_content: str) -> Tuple[bool, Optional[str]]:
        if not patch_content or not patch_content.strip():
            return False, "Empty patch content."
        workspace_dir = cls.get_project_workspace_dir(project_id)
        check_res = subprocess.run(
            ["git", "apply", "--check", "-"],
            cwd=workspace_dir,
            input=patch_content.replace("\r\n", "\n").encode("utf-8"),
            capture_output=True,
        )
        if check_res.returncode != 0:
            return False, check_res.stderr.decode("utf-8", errors="ignore").strip() or "git apply --check failed."
        return True, None

    @classmethod
    def apply_patch_in_workspace(
        cls, project_id: str, patch_content: str, commit_message: str = "Applied Necromancer revival patch"
    ) -> Tuple[bool, Optional[str], Optional[str]]:
        """
        Validates and atomically applies a unified diff in the isolated workspace,
        then commits the changes. Never overwrites files directly on failure.
        Returns (success, result_commit_sha, error_message).
        """
        workspace_dir = cls.get_project_workspace_dir(project_id)
        normalized_patch = patch_content.replace("\r\n", "\n")

        valid, err = cls.validate_patch_in_workspace(project_id, normalized_patch)
        if not valid:
            return False, None, err

        apply_res = subprocess.run(
            ["git", "apply", "-"],
            cwd=workspace_dir,
            input=normalized_patch.encode("utf-8"),
            capture_output=True,
        )
        if apply_res.returncode != 0:
            subprocess.run(["git", "checkout", "--", "."], cwd=workspace_dir, capture_output=True)
            return False, None, apply_res.stderr.decode("utf-8", errors="ignore").strip() or "git apply failed."

        subprocess.run(["git", "add", "-A"], cwd=workspace_dir, check=True, capture_output=True)
        subprocess.run(["git", "commit", "-m", commit_message], cwd=workspace_dir, check=True, capture_output=True)
        new_sha = cls.get_head_commit(project_id)
        return True, new_sha, None

    @classmethod
    def rollback_to_commit(cls, project_id: str, commit_sha: str) -> bool:
        """
        Restores tracked files to commit_sha and removes untracked files/directories
        created during patching or test execution.
        """
        workspace_dir = cls.get_project_workspace_dir(project_id)
        reset_res = subprocess.run(
            ["git", "reset", "--hard", commit_sha],
            cwd=workspace_dir,
            capture_output=True,
            text=True,
        )
        clean_res = subprocess.run(
            ["git", "clean", "-fd"],
            cwd=workspace_dir,
            capture_output=True,
            text=True,
        )
        return reset_res.returncode == 0 and clean_res.returncode == 0
